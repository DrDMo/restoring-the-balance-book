"""Tests of RB1-RB7 as fixed in DESIGN.md. Writes results/results.md (every number the book reports)."""
import numpy as np, pandas as pd, statsmodels.api as sm
from scipy import stats
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = []


def say(*a):
    OUT.append(" ".join(str(x) for x in a))


def km(durations, events, at):
    """Kaplan-Meier survival S(at) (probability not yet restored)."""
    d, e = np.asarray(durations), np.asarray(events)
    s = 1.0
    for t in sorted(set(d[e == 1])):
        if t > at:
            break
        n = (d >= t).sum()
        s *= 1 - ((d == t) & (e == 1)).sum() / n
    return s


def logit(r, xs, label, y="event"):
    d = r.dropna(subset=xs + [y]).copy()
    d["log_t"] = np.log(d.t_since)
    X = sm.add_constant(d[xs + ["log_t"]].astype(float))
    m = sm.Logit(d[y], X).fit(disp=0, cov_type="cluster", cov_kwds={"groups": pd.factorize(d.country)[0]})
    say(f"\n**{label}** (N = {len(d)} country-years, {int(d[y].sum())} events, {d.country.nunique()} countries)")
    say("| term | coef | SE | 95% CI | p |\n|---|---|---|---|---|")
    ci = m.conf_int()
    for k in m.params.index:
        say(f"| {k} | {m.params[k]:.3f} | {m.bse[k]:.3f} | [{ci.loc[k,0]:.3f}, {ci.loc[k,1]:.3f}] | {m.pvalues[k]:.3f} |")
    return m


def main():
    e = pd.read_csv(ROOT / "results/episodes.csv")
    r = pd.read_csv(ROOT / "results/riskset.csv")
    s = pd.read_csv(ROOT / "results/qe_spells.csv")
    ended = e[~e.censored].copy()
    say("# Results (generated by analysis/models.py)\n")
    say("## Descriptives")
    say(f"Backsliding episodes (ERT prch, start>=1900): {len(e)}; ended by 2022 (at risk): {len(ended)}; "
        f"censored/ongoing: {e.censored.sum()}; countries: {e.country.nunique()}")
    say(f"Outcomes (all episodes): {e.outcome.value_counts().sort_index().to_dict()}  (1 breakdown, 2 preempted, 4 averted, 6 censored)")
    say(f"Restored (primary): {ended.restoration.notna().sum()} of {len(ended)}")
    for col in ["rest_tol02", "rest_tol10", "rest_nocred", "rest_half", "uturn"]:
        say(f"  alt {col}: {ended[col].notna().sum()} of {len(ended)}")
    for b, g in ended.groupby("breakdown"):
        say(f"  breakdown={b}: n={len(g)}, restored={g.restoration.notna().sum()}")
    ended["ttr"] = np.where(ended.restoration.notna(), ended.restoration - ended.end, ended.stop - ended.end)
    ended["ev"] = ended.restoration.notna().astype(int)
    say(f"Median depth (EDI): {ended.depth.median():.3f}; median duration (years): {ended.duration.median():.1f}")
    say(f"By era of end: {ended.groupby((ended.end // 25) * 25).agg(n=('ev', 'size'), restored=('ev', 'sum')).to_dict('index')}")
    say(f"Post-1990 ended episodes: {(ended.end >= 1990).sum()}, restored {ended[ended.end >= 1990].ev.sum()}")

    say("\n## RB1 Asymmetry")
    S10 = km(ended.ttr, ended.ev, 10)
    S5, S1, S3, S20 = (km(ended.ttr, ended.ev, k) for k in (5, 1, 3, 20))
    rest = ended[ended.ev == 1]
    say(f"KM share restored within 1/3/5/10/20 years of end: {1-S1:.3f} / {1-S3:.3f} / {1-S5:.3f} / {1-S10:.3f} / {1-S20:.3f}")
    say(f"Median years end->restoration among restored: {rest.ttr.median():.1f} (IQR {rest.ttr.quantile(.25):.0f}-{rest.ttr.quantile(.75):.0f}); "
        f"median episode duration among restored: {rest.duration.median():.1f}; all ended: {ended.duration.median():.1f}")
    a, b = (1 - S10) < 0.5, rest.ttr.median() > rest.duration.median()
    say(f"Criterion (a) <half restored within 10y: {a}; (b) restoration slower than decline: {b} -> RB1 {'supported' if a and b else 'partially supported' if a or b else 'not supported'}")
    for bk, g in ended.groupby("breakdown"):
        say(f"  breakdown={bk}: KM restored within 10y {1-km(g.ttr, g.ev, 10):.3f}; median ttr restored {g[g.ev==1].ttr.median()}")
    say(f"Vol. 2 spells: {len(s[~s.provisional])} non-provisional, {int(s[~s.provisional].recovered.sum())} recovered; "
        f"median duration {s[~s.provisional].duration.median()}")

    base = ["log_gdp", "depth", "breakdown"]
    say("\n## Baseline hazard model")
    logit(r, base, "Baseline: restoration hazard")

    say("\n## RB2 Demand ebb")
    rr = r.copy()
    sd = rr.dagp.std()
    rr["dagp_z"] = rr.dagp / sd
    say(f"dAGP SD in risk set: {sd:.3f}; years with dAGP: {rr.dagp.notna().sum()}; events among them: {int(rr[rr.dagp.notna()].event.sum())}")
    m2 = logit(rr, ["dagp_z"] + base, "RB2 primary: dAGP (z)")
    logit(rr, ["agp"] + base, "RB2 secondary: AGP level")
    logit(rr, ["dagp_z"], "RB2 bivariate dAGP")
    # Vol. 2 spells
    say("\nRB2 on Vol. 2 spells: recovered vs not, demand change at onset (from Vol. 2 design): see QE7; AGP at recovery checked below")

    say("\n## RB3 Electoral reopening")
    logit(r, ["turnover"] + base, "RB3 primary: turnover election since end (incl. year t)")
    logit(r, ["turnover_l1"] + base, "RB3 check: turnover election strictly before t")

    say("\n## RB4 Sequence")
    paths = ["vertical", "horizontal", "diagonal"]
    firsts = []
    for _, x in ended.iterrows():
        ys = {p: x[f"{p}_rest"] for p in paths if x[f"{p}_lost"] and pd.notna(x[f"{p}_rest"])}
        if len(ys) >= 2:
            m = min(ys.values())
            w = [p for p, v in ys.items() if v == m]
            firsts.append(w[0] if len(w) == 1 else "tie")
    fc = pd.Series(firsts).value_counts().to_dict()
    n_ = len(firsts)
    say(f"Episodes with >=2 lost and >=2 restored pathways: {n_}; first restored: {fc}")
    lostc = {p: int(ended[f'{p}_lost'].sum()) for p in paths}
    restc = {p: int(ended[f'{p}_rest'].notna().sum()) for p in paths}
    say(f"Pathways lost (ended episodes): {lostc}; restored: {restc}")
    v = fc.get("vertical", 0)
    if n_:
        bt = stats.binomtest(v, n_, 1 / 3, alternative="greater")
        modal = max(fc, key=fc.get)
        say(f"Vertical-first {v}/{n_} = {v/n_:.3f}; binomial p (H1 > 1/3) = {bt.pvalue:.3f}; modal first = {modal}")

    say("\n## RB5 Institutional anchors")
    logit(r, ["jucon_end"] + base, "RB5a: judicial constraints at end")
    logit(r, ["party_end"] + base, "RB5b: party institutionalization at end")
    logit(r, ["jucon_end", "party_end"] + base, "RB5 joint")

    say("\n## RB6 Mobilization")
    logit(r, ["demmob_l1"] + base, "RB6: pro-democracy mobilization (t-1)")

    say("\n## Combined model")
    logit(r, ["turnover", "jucon_end", "party_end", "demmob_l1"] + base, "All supply-side terms")

    say("\n## RB7 Durability")
    rs = e[e.restoration.notna()].copy()
    obs = rs[rs.relapse_observed == True]
    say(f"Restored episodes: {len(rs)}; relapse status observable (10y window or relapse seen): {len(obs)}; relapsed: {int(obs.relapse.sum())}")
    tab = pd.crosstab(obs.horiz_restored_at_rest, obs.relapse)
    say(f"Horizontal restored at restoration x relapse:\n{tab.to_string()}")
    if tab.shape == (2, 2):
        o, p = stats.fisher_exact(tab.values, alternative="less" if True else "two-sided")
        # rows False/True, cols False/True: H1 relapse lower when horizontal restored
        a_ = tab.loc[True, True] / tab.loc[True].sum()
        b_ = tab.loc[False, True] / tab.loc[False].sum()
        p1 = stats.fisher_exact([[tab.loc[True, True], tab.loc[True, False]], [tab.loc[False, True], tab.loc[False, False]]], alternative="less")[1]
        say(f"Relapse share with horizontal restored {a_:.3f} vs without {b_:.3f}; Fisher one-sided p = {p1:.3f}")
    ag = obs.dropna(subset=["agp_at_rest"])
    say(f"With AGP at restoration: {len(ag)} (relapsed {int(ag.relapse.sum())}); mean AGP relapsed {ag[ag.relapse==True].agp_at_rest.mean():.3f} vs not {ag[ag.relapse==False].agp_at_rest.mean():.3f}")

    (ROOT / "results/results.md").write_text("\n".join(OUT), encoding="utf8")
    print("\n".join(OUT))


if __name__ == "__main__":
    main()
